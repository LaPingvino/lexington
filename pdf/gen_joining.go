//go:build ignore

// gen_joining writes joining.go: the characters that join their
// neighbours (Joining_Type D, R or L in the Unicode Character Database's
// ArabicShaping.txt), as a unicode.RangeTable.
//
//	go run gen_joining.go [ArabicShaping.txt]
//
// Without a file it reads the latest from unicode.org.
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const source = "https://www.unicode.org/Public/UCD/latest/ucd/ArabicShaping.txt"

func main() {
	var in io.Reader
	if len(os.Args) > 1 {
		f, err := os.Open(os.Args[1])
		if err != nil {
			log.Fatal(err)
		}
		defer f.Close()
		in = f
	} else {
		resp, err := http.Get(source)
		if err != nil {
			log.Fatal(err)
		}
		defer resp.Body.Close()
		in = resp.Body
	}
	var version string
	var joining []rune
	sc := bufio.NewScanner(in)
	for sc.Scan() {
		line := sc.Text()
		if version == "" && strings.HasPrefix(line, "# ArabicShaping-") {
			version = strings.TrimSuffix(strings.TrimPrefix(line, "# ArabicShaping-"), ".txt")
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		f := strings.Split(line, ";")
		if len(f) < 3 {
			continue
		}
		switch strings.TrimSpace(f[2]) {
		case "D", "R", "L":
			r, err := strconv.ParseUint(strings.TrimSpace(f[0]), 16, 32)
			if err != nil {
				log.Fatal(err)
			}
			joining = append(joining, rune(r))
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	sort.Slice(joining, func(i, j int) bool { return joining[i] < joining[j] })
	type span struct{ lo, hi rune }
	var spans []span
	for _, r := range joining {
		if n := len(spans); n > 0 && spans[n-1].hi+1 == r {
			spans[n-1].hi = r
			continue
		}
		spans = append(spans, span{r, r})
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by gen_joining.go from ArabicShaping-%s.txt; DO NOT EDIT.\n\n", version)
	b.WriteString("package pdf\n\nimport \"unicode\"\n\n")
	b.WriteString("// joining are the characters that join their neighbours (Joining_Type\n")
	b.WriteString("// D, R or L): Arabic, Syriac, N'Ko, Mongolian and the other joining\n")
	b.WriteString("// scripts, which print right only shaped.\n")
	b.WriteString("var joining = &unicode.RangeTable{\n\tR16: []unicode.Range16{\n")
	for _, s := range spans {
		if s.hi <= 0xFFFF {
			fmt.Fprintf(&b, "\t\t{0x%04x, 0x%04x, 1},\n", s.lo, s.hi)
		}
	}
	b.WriteString("\t},\n\tR32: []unicode.Range32{\n")
	for _, s := range spans {
		if s.hi > 0xFFFF {
			fmt.Fprintf(&b, "\t\t{0x%x, 0x%x, 1},\n", s.lo, s.hi)
		}
	}
	b.WriteString("\t},\n}\n")
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("joining.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
